func validateSVG(name string, data []byte) error {
	svg, err := ui.ParseSVG(data)
	if err != nil {
		return fmt.Errorf("%s.svg: %w", name, err)
	}
	if w, h := svg.Size(); w != 24 || h != 24 {
		return fmt.Errorf("%s.svg: expected Lucide's 24x24 canvas, got %gx%g", name, w, h)
	}
	return nil
}

func render(cfg Config, sources map[string][]byte) ([]byte, error) {
	var code bytes.Buffer
	if _, err := fmt.Fprintf(&code, "// Code generated by icongen; DO NOT EDIT.\n\npackage %s\n\n", cfg.packageName()); err != nil {
		return nil, err
	}
	if len(cfg.Icons) == 0 {
		return format.Source(code.Bytes())
	}
	code.WriteString(`import (
	"sync"

	"github.com/egoist/mygo/ui"
)

type lazyIcon struct {
	once sync.Once
	svg *ui.SVG
}

func (i *lazyIcon) get(source string) *ui.SVG {
	i.once.Do(func() { i.svg = ui.MustParseSVG([]byte(source)) })
	return i.svg
}

`)
	for _, name := range cfg.Icons {
		symbol, err := identifier(name)
		if err != nil {
			return nil, err
		}
		svg, ok := sources[name]
		if !ok {
			return nil, fmt.Errorf("missing SVG for %q; run sync", name)
		}
		if _, err := fmt.Fprintf(&code, "func %s() *ui.SVG { return cache%s.get(%q) }\n\nvar cache%s lazyIcon\n\n", symbol, symbol, string(svg), symbol); err != nil {
			return nil, err
		}
	}
	return format.Source(code.Bytes())
}

// readEmbeddedSVGs 从生成的访问函数提取 SVG 字符串，不执行代码；格式异常的函数由 Sync 恢复。
func readEmbeddedSVGs(dir string) (map[string][]byte, error) {
	file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, codeFile), nil, 0)
	if err != nil {
		return nil, err
	}
	sources := make(map[string][]byte)
	for _, decl := range file.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv != nil || fn.Body == nil || len(fn.Body.List) != 1 {
			continue
		}
		ret, ok := fn.Body.List[0].(*ast.ReturnStmt)
		if !ok || len(ret.Results) != 1 {
			continue
		}
		call, ok := ret.Results[0].(*ast.CallExpr)
		if !ok || len(call.Args) != 1 {
			continue
		}
		selector, ok := call.Fun.(*ast.SelectorExpr)
		if !ok || selector.Sel.Name != "get" {
			continue
		}
		cache, ok := selector.X.(*ast.Ident)
		if !ok || cache.Name != "cache"+fn.Name.Name {
			continue
		}
		literal, ok := call.Args[0].(*ast.BasicLit)
		if !ok || literal.Kind != token.STRING {
			continue
		}
		source, err := strconv.Unquote(literal.Value)
		if err != nil {
			continue
		}
		sources[fn.Name.Name] = []byte(source)
	}
	return sources, nil
}

func localSources(dir string, cfg Config) (map[string][]byte, error) {
	locked, err := readLock(dir, cfg)
	if err != nil {
		return nil, err
	}
	if locked == nil {
		return nil, fmt.Errorf("%s is missing; run sync first", lockFile)
	}
	if len(locked.Icons) != len(cfg.Icons) {
		return nil, fmt.Errorf("icon list differs from %s; run sync", lockFile)
	}
	embedded, err := readEmbeddedSVGs(dir)
	if err != nil {
		return nil, fmt.Errorf("%s: %w; run sync to restore generated sources", codeFile, err)
	}
	sources := make(map[string][]byte)
	for _, name := range cfg.Icons {
		symbol, _ := identifier(name)
		data, ok := embedded[symbol]
		if !ok {
			return nil, fmt.Errorf("%s is missing SVG source for %q; run sync", codeFile, name)
		}
		if locked.Icons[name] != digest(data) {
			return nil, fmt.Errorf("%s SVG source differs from the lock; run sync to restore upstream SVGs", name)
		}
		if err := validateSVG(name, data); err != nil {
			return nil, err
		}
		sources[name] = data
	}
	license, err := os.ReadFile(filepath.Join(dir, licenseFile))
	if err != nil {
		return nil, err
	}
	if digest(license) != locked.LicenseSHA256 {
		return nil, fmt.Errorf("%s differs from the lock; run sync", licenseFile)
	}
	return sources, nil
}

func generateLocal(dir string, cfg Config, check bool, out io.Writer) error {
	sources, err := localSources(dir, cfg)
	if err != nil {
		return err
	}
	code, err := render(cfg, sources)
	if err != nil {
		return err
	}
	if check {
		existing, err := os.ReadFile(filepath.Join(dir, codeFile))
		if err != nil {
			return err
		}
		if !bytes.Equal(existing, code) {
			return fmt.Errorf("%s is stale; run generate", codeFile)
		}
		_, err = fmt.Fprintf(out, "Checked %d icons (offline)\n", len(cfg.Icons))
		return err
	}
	if err := writeFiles(dir, map[string][]byte{codeFile: code}); err != nil {
		return err
	}
	if _, err := fmt.Fprintf(out, "Generated %d accessors (offline)\n", len(cfg.Icons)); err != nil {
		return fmt.Errorf("write generation status (files already updated): %w", err)
	}
	return nil
}

// writeFiles 先暂存所有变更，再替换目标文件。
func writeFiles(dir string, files map[string][]byte) (err error) {
	staged := map[string]string{}
	defer func() {
		for _, temp := range staged {
			if removeErr := os.Remove(temp); removeErr != nil && !errors.Is(removeErr, os.ErrNotExist) {
				err = errors.Join(err, fmt.Errorf("remove temporary file: %w", removeErr))
			}
		}
	}()
	for name, data := range files {
		path := filepath.Join(dir, name)
		existing, err := os.ReadFile(path)
		if err == nil && bytes.Equal(existing, data) {
			continue
		}
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return err
		}
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			return err
		}
		f, err := os.CreateTemp(filepath.Dir(path), ".icongen-*")
		if err != nil {
			return err
		}
		staged[path] = f.Name()
		_, writeErr := f.Write(data)
		closeErr := f.Close()
		if writeErr != nil {
			return writeErr
		}
		if closeErr != nil {
			return closeErr
		}
		if err := os.Chmod(f.Name(), 0644); err != nil {
			return err
		}
	}
	for path, temp := range staged {
		if err := os.Rename(temp, path); err != nil {
			return err
		}
	}
	return nil
}
